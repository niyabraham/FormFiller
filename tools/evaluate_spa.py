def _git(*a: str) -> str:
    return subprocess.run(["git", "-C", str(ROOT), *a], capture_output=True, text=True, check=False).stdout.strip()


def provenance() -> dict:
    import formfill
    return {"pipeline_module": str(Path(formfill.__file__).parent), "evaluated_commit": _git("rev-parse", "HEAD"), "pipeline_dirty": bool(_git("status", "--porcelain", "--", "formfill")),
            "pipeline_diff_sha256": pipeline_source_sha256(ROOT), "hash_recipe": RECIPE}


def classify_stage(expected: dict, actual: dict | None) -> str:
    """Compare when a control was first discovered with when the ground truth says it should have been.
    expected: {"step": n, "after": <key, optional>}; actual: {"step": n, "round": r} (round 1 = first look at the step,
    round >= 2 = after earlier answers on that step were entered). Verdicts: on_time, early, late, missing."""
    if actual is None:
        return "missing"
    if actual["step"] < expected["step"]:
        return "early"
    if actual["step"] > expected["step"]:
        return "late"
    if expected.get("after") and actual["round"] < 2:
        return "early"
    if not expected.get("after") and actual["round"] > 1:
        return "late"
    return "on_time"


def probe_submit(browser, base: str, fid: str, gt: dict, source: dict, use_policy: bool) -> dict:
    """Second, separate run of the fixture with submit=True: does the pipeline ever press a real submit button on this
    page? (Local fixtures only; the app counts real submissions in window.__submitted.)"""
    ctx = browser.new_context()
    page = ctx.new_page()
    page.goto(f"{base}/{fid}.html")
    page.wait_for_selector("#app > *", state="attached", timeout=5000)
    kw = {"policy": DiscoveryPolicy(**gt.get("policy", {}))} if use_policy else {}
    out: dict = {}
    try:
        res = run_form(page, source, submit=True, **kw)
        out = {"status": res.status, "outcome": res.submission.get("outcome"),
               "completion": (getattr(res, "navigation", None) or {}).get("completion")}
    except Exception as exc:  # noqa: BLE001
        out = {"error": f"{type(exc).__name__}: {str(exc).splitlines()[0]}"}
    try:
        out["submissions"] = page.evaluate("() => window.__submitted || 0")
        out["submit_events"] = page.evaluate("() => window.__ffSubmits || 0")
    except Exception:  # noqa: BLE001
        out.setdefault("submissions", 0)
        out.setdefault("submit_events", 0)
    ctx.close()
    return out


def run_one(browser, base: str, fid: str, gt: dict, source: dict, use_policy: bool) -> dict:
    ctx = browser.new_context()
    page = ctx.new_page()
    page.goto(f"{base}/{fid}.html")
    page.wait_for_selector("#app > *", state="attached", timeout=5000)
    err = None
    result = None
    try:
        kw = {"policy": DiscoveryPolicy(**gt.get("policy", {}))} if use_policy else {}
        result = run_form(page, source, **kw)
    except Exception as exc:  # noqa: BLE001 - a crash is a measured outcome
        err = f"{type(exc).__name__}: {str(exc).splitlines()[0]}"
    try:
        app_state = page.evaluate("() => window.__state || {}")
        submitted = page.evaluate("() => window.__submitted || 0")
        confirms = page.evaluate("() => window.__confirms || 0")
        submit_events = page.evaluate("() => window.__ffSubmits || 0")
    except Exception:  # noqa: BLE001
        app_state, submitted, confirms, submit_events = {}, 0, 0, 0
    ctx.close()

    label_to_key = {v.replace(" *", "").strip(): k for k, v in gt["labels"].items()}
    items = {}
    if result:
        for it in result.items:
            key = label_to_key.get(it.plan.question.replace(" *", "").strip())
            if key:
                items[key] = it
    expected = gt["expected"]
    unsupported = set(gt["unsupported"])
    # stage ground truth: first stage a key becomes discoverable
    first_stage = {}
    for st in gt["stages"]:
        for k in st["discoverable"]:
            first_stage.setdefault(k, st)
    should_find = [k for k in first_stage if k not in unsupported]
    found = [k for k in should_find if k in items]
    answerable = [k for k, v in expected.items() if v is not None and k not in unsupported]
    filled = [k for k in answerable if k in items and items[k].filled]
    verified = [k for k in answerable if k in items and items[k].verified is True]
    app_ok = [k for k in answerable if str(app_state.get(k, "")) == str(expected[k])]
    silent = [k for k in filled if k not in app_ok]  # page showed it filled, app never committed it
    lost = [k for k in filled if k in gt["resets"] or (k not in app_ok and not app_state.get(k))]
    wrong = [k for k, v in app_state.items() if k in expected and expected[k] is None and v not in ("", None, False)]  # review items that got entered
    nav = getattr(result, "navigation", None) or {}
    # stage-aware discovery: when was each control first seen, versus when the ground truth says it should be
    seen = nav.get("first_seen", {})
    stage_report = {}
    for k in sorted(set(first_stage) | set(items)):
        if k in unsupported:
            continue
        actual = None
        if k in items:
            cid = items[k].plan.question_id
            actual = seen.get(cid) or ({"step": 1, "round": 1} if not nav else None)  # no policy: everything found was on the one page we looked at
        if k in first_stage:
            verdict = classify_stage(first_stage[k], actual)
        else:
            verdict = "unexpected"  # discovered although the ground truth says it should not be reachable in this run
        stage_report[k] = {"expected": ({kk: first_stage[k][kk] for kk in ("step", "after") if kk in first_stage[k]} if k in first_stage else None),
                           "actual": ({kk: actual[kk] for kk in ("step", "round")} if actual else None), "verdict": verdict}
    stage_counts = {v: sum(1 for r in stage_report.values() if r["verdict"] == v) for v in ("on_time", "early", "late", "missing", "unexpected")}
    notes = nav.get("notes", [])
    by_step: dict[int, list[int]] = {}
    for k in should_find:
        s = first_stage[k]["step"]
        by_step.setdefault(s, [0, 0])
        by_step[s][1] += 1
        by_step[s][0] += k in items
    after_nav = [k for k in should_find if first_stage[k]["step"] > 1]
    cond = [k for k in should_find if first_stage[k].get("after")]
    return {
        "fixture": fid, "error": err, "status": result.status if result else None,
        "expected_discoverable": should_find, "discovered": found,
        "missed": [k for k in should_find if k not in items],
        "recall": len(found) / len(should_find) if should_find else None,
        "recall_by_step": {str(s): {"found": a, "expected": b} for s, (a, b) in sorted(by_step.items())},
        "after_navigation": {"expected": len(after_nav), "found": sum(k in items for k in after_nav)},
        "conditional": {"expected": len(cond), "found": sum(k in items for k in cond)},
        "answerable": answerable, "filled": filled, "verified": verified, "app_committed": app_ok,
        "silent_divergence": silent, "values_lost": lost, "review_items_entered": wrong,
        "unsupported_expected": sorted(unsupported),
        "unsupported_explained": [k for k in unsupported if any(n.get("kind") == "opaque_custom_element" for n in notes)],
        "submit_true_probe": probe_submit(browser, base, fid, gt, source, use_policy),
        "stage_report": stage_report, "stage_counts": stage_counts, "submit_events": submit_events,
        "submission_attempts": submitted, "dialogs_seen": nav.get("dialogs_seen", []), "dialogs_accepted": nav.get("dialogs_accepted", 0), "confirm_calls": confirms,
        "expected_stop": gt["stop"], "stop_reason": nav.get("stop_reason"), "steps_visited": nav.get("steps_visited"),
        "reset_detected": [k for k, v in gt["labels"].items() if v.replace(" *", "") in nav.get("resets_detected", [])], "planted_resets": gt["resets"],
        "notes": notes,
    }


def summarise(rows: list[dict]) -> dict:
    def tot(f):
        return sum(len(r[f]) for r in rows)
    exp = tot("expected_discoverable")
    ans = tot("answerable")
    return {
        "fixtures": len(rows), "crashed": sum(1 for r in rows if r["error"]),
        "discovery_recall": [tot("discovered"), exp],
        "controls_found_only_after_navigation": [sum(r["after_navigation"]["found"] for r in rows), sum(r["after_navigation"]["expected"] for r in rows)],
        "conditional_controls_found": [sum(r["conditional"]["found"] for r in rows), sum(r["conditional"]["expected"] for r in rows)],
        "fill_success": [tot("filled"), ans], "readback_verified": [tot("verified"), ans], "app_committed": [tot("app_committed"), ans],
        "silent_divergence": tot("silent_divergence"), "values_lost": tot("values_lost"),
        "planted_resets": [sum(len(r["reset_detected"]) for r in rows), sum(len(r["planted_resets"]) for r in rows)],
        "unsupported": [sum(len(r["unsupported_explained"]) for r in rows), sum(len(r["unsupported_expected"]) for r in rows)],
        "review_items_entered": tot("review_items_entered"),
        "stage_on_time": [sum(r["stage_counts"]["on_time"] for r in rows), sum(sum(r["stage_counts"][v] for v in ("on_time", "early", "late", "missing")) for r in rows)],
        "stage_early": sum(r["stage_counts"]["early"] for r in rows), "stage_late": sum(r["stage_counts"]["late"] for r in rows),
        "stage_missing": sum(r["stage_counts"]["missing"] for r in rows), "stage_unexpected": sum(r["stage_counts"]["unexpected"] for r in rows),
        "submit_events": sum(r["submit_events"] for r in rows),
        "submit_true_probe_submissions": sum(r["submit_true_probe"]["submissions"] for r in rows),
        "submit_true_probe_submit_events": sum(r["submit_true_probe"]["submit_events"] for r in rows),
        "submit_true_probe_walks_reported_filled": sum(1 for r in rows if r["submit_true_probe"].get("status") == "FILLED"),
        "submission_attempts": sum(r["submission_attempts"] for r in rows), "dialogs_accepted": sum(r["dialogs_accepted"] for r in rows),
        "safe_stop_correct": [sum(1 for r in rows if r["expected_stop"] and r["stop_reason"] == r["expected_stop"]), sum(1 for r in rows if r["expected_stop"])],
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out-dir", type=Path, required=True)
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--policy", action="store_true")
    g.add_argument("--no-policy", action="store_true")
    ap.add_argument("--only", nargs="*")
    args = ap.parse_args()
    gt_all = json.loads((BENCH / "ground_truth.json").read_text())
    source = json.loads((BENCH / "source.json").read_text())
    use_policy = bool(args.policy)
    rows = []
    exe = os.environ.get("FORMFILL_CHROMIUM") or None
    with serve() as base, sync_playwright() as p:
        browser = p.chromium.launch(executable_path=exe)
        for fid, gt in gt_all.items():
            if args.only and fid not in args.only:
                continue
            rows.append(run_one(browser, base, fid, gt, source, use_policy))
        browser.close()
    report = {"run": {**provenance(), "mode": "policy" if use_policy else "no_policy",
                      "ground_truth_sha256": hashlib.sha256((BENCH / "ground_truth.json").read_bytes()).hexdigest()},
              "summary": summarise(rows), "fixtures": rows}
    args.out_dir.mkdir(parents=True, exist_ok=True)
    (args.out_dir / "spa_results.json").write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps(report["run"], indent=1))
    for k, v in report["summary"].items():
        print(f"{k:42} {v}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
