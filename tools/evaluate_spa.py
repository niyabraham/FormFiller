"""Browser-reliability evaluation on the local SPA fixtures (Phase 3C). Kept separate from retrieval evaluation:
it measures discovery, navigation, filling and verification, not which JSON path answers which question.

    python tools/evaluate_spa.py --out-dir benchmarks/spa/results/after [--policy | --no-policy]

--no-policy runs the pipeline exactly as before Phase 3C (single page, no navigation); --policy enables the
step-navigation policy. Ground truth: benchmarks/spa/ground_truth.json (generated by benchmarks/spa/build_fixtures.py).
Truth about what the app holds comes from the page's own window.__state, not from the DOM the pipeline reads.
"""

